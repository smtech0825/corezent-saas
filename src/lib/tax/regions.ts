/**
 * @함수명: buildRegionCode
 * @설명: 시·도+시·군·구 이름으로 규제지역 매칭 키(region_code)를 조립합니다.
 *        계산기와 관리자 규제지역 입력 화면이 반드시 이 함수를 함께 써야 코드가 일치합니다.
 * @매개변수: sido - 시·도 명칭 / sigungu - 시·군·구 명칭
 * @반환값: 'sido|sigungu' 형식 코드 (세종처럼 시·군·구가 없는 곳은 시·도 이름 그대로)
 */
export function buildRegionCode(sido: string, sigungu: string): string {
  return sido === sigungu ? sido : `${sido}|${sigungu}`
}

/**
 * @함수명: findSigunguList
 * @설명: 시·도 이름으로 시·군·구 목록을 찾습니다. 없으면 null.
 */
export function findSigunguList(sido: string): string[] | null {
  return REGIONS.find((r) => r.sido === sido)?.sigungu ?? null
}

/**
 * @함수명: isKnownRegion
 * @설명: 시·도/시·군·구 조합이 목록에 있는지 검사합니다(주소 직접 입력 차단용 서버 검증).
 */
export function isKnownRegion(sido: string, sigungu: string): boolean {
  return findSigunguList(sido)?.includes(sigungu) ?? false
}
